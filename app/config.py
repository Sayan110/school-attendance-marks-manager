def app_root() -> Path:
    """Directory containing bundled resources (works frozen and from source)."""
    if getattr(sys, "frozen", False):
        return Path(getattr(sys, "_MEIPASS", Path(sys.executable).resolve().parent))
    return Path(__file__).resolve().parent.parent


def executable_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return app_root()


def data_dir() -> Path:
    """Writable per-user data directory. Never the install directory."""
    override = os.environ.get("SVSM_DATA_DIR")
    if override:
        base = Path(override).expanduser()
    else:
        local_app_data = os.environ.get("LOCALAPPDATA")
        base = (
            Path(local_app_data) / "ShikshaVikashSchoolManager"
            if local_app_data
            else Path.home() / ".shiksha_vikash_school_manager"
        )
    return base


def ensure_data_dirs() -> dict[str, Path]:
    base = data_dir()
    paths = {
        "base": base,
        "data": base / "data",
        "backups": base / "backups",
        "exports": base / "exports",
        "logs": base / "logs",
    }
    for path in paths.values():
        path.mkdir(parents=True, exist_ok=True)
    return paths


def database_path() -> Path:
    env_path = os.environ.get("SVSM_DB_PATH")
    if env_path:
        path = Path(env_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        return path
    return ensure_data_dirs()["data"] / "school_manager.db"


def default_backup_dir() -> Path:
    return ensure_data_dirs()["backups"]


def default_export_dir() -> Path:
    return ensure_data_dirs()["exports"]


def icon_path() -> Path:
    candidate = app_root() / APP_ICON_FILENAME
    return candidate


def theme_palette(name: str) -> dict:
    return THEME_DARK if str(name).lower() == "dark" else THEME_LIGHT
